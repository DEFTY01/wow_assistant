// The only file the bridge ever writes inside the game folder: AzerothMCP_Data/Data.lua.
// It holds one assignment of plain Lua literals that the addon shows after the next /reload.
import { existsSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { assertInside } from "./config.ts";
import { toLua } from "./lua.ts";
import { addonsDir } from "./paths.ts";

export interface InboxItem { title: string; text: string }
export interface Inbox { notes: InboxItem[]; goals: InboxItem[] }

const MAX_BYTES = 256 * 1024;

export function inboxDir(wowDir: string): string {
  return join(addonsDir(wowDir), "AzerothMCP_Data");
}

export function writeInbox(wowDir: string, inbox: Inbox): { file: string; bytes: number } {
  const dir = inboxDir(wowDir);
  if (!existsSync(join(dir, "AzerothMCP_Data.toc"))) {
    throw new Error("The AzerothMCP_Data addon is not installed. Run `npm run install-addons` in mcp/ with the game closed.");
  }
  const file = assertInside(join(dir, "Data.lua"), dir);
  const body =
    "-- Generated by azeroth-mcp. Overwritten on every write; do not edit.\n" +
    `AzerothMCP_Inbox = ${toLua({ generated: Math.floor(Date.now() / 1000), notes: inbox.notes, goals: inbox.goals })}\n`;
  const bytes = Buffer.byteLength(body, "utf8");
  if (bytes > MAX_BYTES) throw new Error(`Inbox too large (${bytes} bytes, max ${MAX_BYTES})`);
  const tmp = file + ".tmp";
  writeFileSync(tmp, body, "utf8");
  renameSync(tmp, file);
  return { file, bytes };
}
