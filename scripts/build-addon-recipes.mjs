// Builds the game data files of the WowAssistant addon:
//   addon/WowAssistant/Recipes.lua   recipes (vendor crafting, profession routes, crafted gear)
//   addon/WowAssistant/GameData.lua  dungeon and quest loot, buffs and consumables (gear, plan)
//
// Sources: the recipe lists saved from Wowhead Forever (data/wowhead/<professionId>.json, see
// scripts/import-recipes.mjs) and, from the local app database, what vendors charge for the
// reagents they sell and the loot table (imported through /api/import/loot). The files are
// generated, not kept in git; run this after a new recipe or loot import:
//   node scripts/build-addon-recipes.mjs [--install]
// --install also copies them into the game's AddOns folder (WOW_DIR from .uploader.env).
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { BUFFS, CONSUMABLE_ITEMS } from "../src/buffData.ts";
import { COOLDOWN, PROFESSIONS, VENDOR_REAGENTS, VENDOR_SOLD } from "../src/craftData.ts";

const root = join(import.meta.dirname, "..");
const dir = join(root, "data", "wowhead");
const out = join(root, "addon", "WowAssistant", "Recipes.lua");
const outData = join(root, "addon", "WowAssistant", "GameData.lua");

const lua = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';
const n = (v) => (v == null ? "nil" : String(v));

// One query against the app's local database (wrangler d1, --local).
function query(sql, what) {
  try {
    const raw = execFileSync(process.execPath, [
      join(root, "node_modules", "wrangler", "bin", "wrangler.js"), "d1", "execute", "wow-assistant", "--local", "--json",
      "--command", sql,
    ], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 << 20 });
    return JSON.parse(raw)[0].results;
  } catch (e) {
    console.warn(`${what}: nem tudtam kiolvasni a helyi adatbázisból:`, e.message);
    return [];
  }
}

// What vendors charge for the reagents they sell (Blizzard item API, stored by the app).
function vendorPrices() {
  const ids = [...VENDOR_SOLD].join(",");
  const rows = query(`SELECT item_id, vendor_buy FROM items WHERE item_id IN (${ids}) AND vendor_buy > 0`, "A kereskedői árak");
  return Object.fromEntries(rows.map((r) => [r.item_id, r.vendor_buy]));
}

// ---------------------------------------------------------------- Recipes.lua

const recipes = [];
const names = {};
const sell = {};
for (const file of readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)).sort()) {
  const d = JSON.parse(readFileSync(join(dir, file), "utf8"));
  for (const [id, [name, price]] of Object.entries(d.i)) {
    if (name) names[id] = name;
    if (price != null && price > 0) sell[id] = price;
  }
  for (const [spell, name, colors, creates, reagents, trainingCost, source] of d.r) {
    // The same filter as the web app's recipe import (src/professions.ts importRecipes):
    // recipes without a product (enchants) still count for skill routes.
    if (!reagents?.length || !Array.isArray(colors) || colors.length !== 4) continue;
    const trainer = (source ?? []).includes(6) && trainingCost != null ? trainingCost : -1;
    recipes.push({
      spell, prof: d.p, orange: Math.max(1, colors[0]), product: creates?.[0] ?? 0,
      min: creates ? Number(creates[1]) || 1 : 1, max: creates ? Number(creates[2] ?? creates[1]) || 1 : 1,
      trainer, cd: COOLDOWN[spell] ?? 0, name, reagents, sources: (source ?? []).join(","),
      yellow: colors[1], grey: colors[3],
    });
  }
}
const vendor = vendorPrices();

const lines = [
  `-- Generated by scripts/build-addon-recipes.mjs on ${new Date().toISOString().slice(0, 10)} from Wowhead Forever data. Do not edit.`,
  "-- recipes: { spell, profession, skill to learn (orange), product (0: none), makes min, makes max,",
  "--            trainer cost (-1: not from a trainer), cooldown seconds, name, { reagent, qty, ... },",
  "--            sources, yellow, grey }",
  "WowAssistantRecipes = {",
  "  professions = {",
  ...Object.entries(PROFESSIONS).map(([id, name]) => `    [${id}] = ${lua(name)},`),
  "  },",
  "  recipes = {",
  ...recipes.map((r) =>
    `    {${r.spell},${r.prof},${r.orange},${r.product},${r.min},${r.max},${r.trainer},${r.cd},${lua(r.name)},{${r.reagents.flat().join(",")}},${lua(r.sources)},${r.yellow},${r.grey}},`),
  "  },",
  "  vendorReagents = {",
  ...[...VENDOR_REAGENTS].map((id) => `    [${id}] = true,`),
  "  },",
  "  vendor = {",
  ...Object.entries(vendor).map(([id, p]) => `    [${id}] = ${p},`),
  "  },",
  "  sell = {",
  ...Object.entries(sell).map(([id, p]) => `    [${id}] = ${p},`),
  "  },",
  "  names = {",
  ...Object.entries(names).map(([id, name]) => `    [${id}] = ${lua(name)},`),
  "  },",
  "}",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${recipes.length} recept, ${Object.keys(vendor).length} kereskedői ár, ${Object.keys(sell).length} vendorár`);

// ---------------------------------------------------------------- GameData.lua

// Wowhead stats -> the damage model's numbers (the same as lootStats in src/gear.ts). Ranged
// weapons (bows, guns, crossbows, thrown) carry their numbers as rgd*, and ranged attack power
// (hunters) as rgdatkpwr. One "+1% hit" is listed as both mlehitpct and rgdhitpct.
// Wowhead Forever gives hit and crit as ratings: the original "+1% hit" items carry hitrtng 10
// and the "+1% crit" ones critstrkrtng 14, so the model's percentages are rating / 10 and / 14.
const HIT_RATING = 10;
const CRIT_RATING = 14;
const pct = (v) => Math.round(v * 100) / 100;
const lootStats = (st) => ({
  agi: st.agi ?? 0, str: st.str ?? 0, ap: st.atkpwr ?? 0, crit: pct((st.critstrkrtng ?? 0) / CRIT_RATING),
  hit: pct((st.hitrtng ?? 0) / HIT_RATING + Math.max(st.mlehitpct ?? 0, st.rgdhitpct ?? 0)), rap: st.rgdatkpwr ?? 0,
  // casters (shamans): intellect, and spell power for damage (any school, or nature)
  int: st.int ?? 0, sp: (st.splpwr ?? 0) + (st.spldmg ?? 0) + (st.natsplpwr ?? 0),
  weapon: st.mlespeed ? [st.mledmgmin, st.mledmgmax, st.mlespeed]
    : st.rgdspeed ? [st.rgddmgmin, st.rgddmgmax, st.rgdspeed] : [],
});
const dungeons = query("SELECT zone_id, name, min_level, max_level, req_level, kind FROM dungeons ORDER BY zone_id", "A dungeonok");
const loot = query(
  "SELECT item_id, zone_id, name, quality, item_level, req_level, slot, item_class, subclass, boss, stats, drop_pct, source, side, quest_level " +
    "FROM loot",
  "A loot",
);
const data = [
  `-- Generated by scripts/build-addon-recipes.mjs on ${new Date().toISOString().slice(0, 10)} from the app's local database. Do not edit.`,
  "WowAssistantData = {",
  "  -- dungeons[zone] = { name, min level, max level, required level, kind }",
  "  dungeons = {",
  ...dungeons.map((d) => `    [${d.zone_id}] = { ${lua(d.name)}, ${d.min_level || 0}, ${d.max_level || 0}, ${d.req_level || 0}, ${lua(d.kind ?? "dungeon")} },`),
  "  },",
  "  -- loot: { item, zone, name, quality, item level, required level, Wowhead slot, class, subclass, boss,",
  "  --         drop %, source, side, quest level, agi, str, ap, crit, hit, weapon min, max, speed,",
  "  --         ranged attack power, intellect, spell power }",
  "  loot = {",
  ...loot.map((r) => {
    const s = lootStats(JSON.parse(r.stats || "{}"));
    const w = s.weapon;
    return `    { ${r.item_id}, ${r.zone_id}, ${lua(r.name)}, ${n(r.quality)}, ${n(r.item_level)}, ${r.req_level || 0}, ${n(r.slot)}, ` +
      `${n(r.item_class)}, ${n(r.subclass)}, ${r.boss ? lua(r.boss) : "nil"}, ${n(r.drop_pct)}, ${lua(r.source ?? "dungeon")}, ` +
      `${r.side ?? 0}, ${n(r.quest_level)}, ${s.agi}, ${s.str}, ${s.ap}, ${s.crit}, ${s.hit}, ${n(w[0])}, ${n(w[1])}, ${n(w[2])}, ${s.rap}, ${s.int}, ${s.sp} },`;
  }),
  "  },",
  "  -- buffs: { id, name, source, group, { { level, label, agi, str, ap, crit, statPct }, ... } }",
  "  buffs = {",
  ...BUFFS.map((b) => `    { ${lua(b.id)}, ${lua(b.name)}, ${lua(b.source)}, ${lua(b.group)}, { ` +
    b.tiers.map((t) => `{ ${t.level}, ${t.label ? lua(t.label) : "nil"}, ${n(t.agi)}, ${n(t.str)}, ${n(t.ap)}, ${n(t.crit)}, ${n(t.statPct)} }`).join(", ") +
    " } },"),
  "  },",
  "  -- consumables[name] = { item, minutes }",
  "  consumables = {",
  ...Object.entries(CONSUMABLE_ITEMS).map(([k, v]) => `    [${lua(k)}] = { ${v.itemId}, ${v.minutes} },`),
  "  },",
  "}",
  "",
];
writeFileSync(outData, data.join("\n"));
console.log(`${outData}: ${dungeons.length} dungeon, ${loot.length} loot`);

if (process.argv.includes("--install")) {
  const env = existsSync(join(root, ".uploader.env")) ? readFileSync(join(root, ".uploader.env"), "utf8") : "";
  const wow = process.env.WOW_DIR ?? env.match(/^WOW_DIR=(.+)$/m)?.[1]?.trim() ?? "F:/World of Warcraft/_forever_";
  for (const file of [out, outData]) {
    const target = join(wow, "Interface", "AddOns", "WowAssistant", basename(file));
    copyFileSync(file, target);
    console.log(`telepítve: ${target}`);
  }
}
