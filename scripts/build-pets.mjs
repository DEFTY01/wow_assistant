// Builds data/wowhead/pets.json from the Wowhead Forever hunter-pets scrape
// (data/wowhead/pets-*.txt + pets-meta.json) and the ability tooltips.
// Usage: node scripts/build-pets.mjs [--fetch]   (--fetch refreshes tooltips)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'data', 'wowhead');
const meta = JSON.parse(readFileSync(join(DIR, 'pets-meta.json'), 'utf8'));
const TIPS = join(DIR, 'pet-tooltips.json');

// spell id -> { rank, tp, ability }
const spells = {};
for (const [key, v] of Object.entries(meta.spell)) {
  const [ability] = key.split('#');
  const [id, tp] = v.split('/').map(Number);
  if (!spells[id]) spells[id] = { id, ability, tp };
  else if (tp > 0) spells[id].tp = tp;
}

let tips = existsSync(TIPS) ? JSON.parse(readFileSync(TIPS, 'utf8')) : {};
if (process.argv.includes('--fetch') || Object.keys(tips).length === 0) {
  for (const id of Object.keys(spells)) {
    if (tips[id] && !process.argv.includes('--fetch')) continue;
    const r = await fetch(`https://nether.wowhead.com/forever/tooltip/spell/${id}`);
    const j = await r.json();
    const t = j.tooltip || '';
    const pick = (re) => (t.match(re) || [])[1];
    tips[id] = {
      name: j.name,
      icon: j.icon,
      rank: Number(pick(/whtt-rank">Rank (\d+)/) || 0),
      level: Number(pick(/Requires level (\d+)/) || 0),
      cost: pick(/<td>(\d+ Focus)<\/td>/) || null,
      cd: pick(/cooldownText-->([^<]+)<!--cooldownText/) || null,
      desc: (pick(/<div class="q">([\s\S]*?)<\/div>/) || '').replace(/<[^>]+>/g, '').trim(),
    };
    await new Promise((res) => setTimeout(res, 120));
  }
  writeFileSync(TIPS, JSON.stringify(tips, null, 1));
}

// rank number per spell id: Wowhead rank, else order within the ability
const byAbility = {};
for (const s of Object.values(spells)) (byAbility[s.ability] ||= []).push(s);
for (const list of Object.values(byAbility)) {
  list.sort((a, b) => (tips[a.id]?.level || 0) - (tips[b.id]?.level || 0) || a.id - b.id);
  list.forEach((s, i) => { s.rank = tips[s.id]?.rank || i + 1; });
}

const rows = readdirSync(DIR).filter((f) => /^pets-\d+\.txt$/.test(f)).sort()
  .flatMap((f) => readFileSync(join(DIR, f), 'utf8').split(/\r?\n/).filter(Boolean));
const beasts = rows.map((line) => {
  const [npc, name, fam, lvl, flags, zone, abil, isNew] = line.split('~');
  let min = 0, max = 0, elite = flags.includes('E');
  if (/^\d/.test(lvl)) { [min, max] = lvl.split('-').map(Number); max ||= min; }
  else if (lvl) elite = true;
  const abilities = [];
  let speed = 200;
  for (const a of abil.split(' ').filter(Boolean)) {
    const [ai, rv] = a.split('.').map(Number);
    const ability = meta.abn[ai];
    if (/Attack/.test(ability)) { speed = rv; continue; }
    const v = meta.spell[`${ability}#${rv}`];
    const id = v ? Number(v.split('/')[0]) : null;
    abilities.push({ ability, rank: id ? spells[id].rank : rv, spell: id });
  }
  return {
    npc: Number(npc), name, family: meta.fams[Number(fam)], min, max,
    rare: flags.includes('R'), elite, zone: meta.zones[Number(zone)].replace(/ \+\d+$/, ''),
    multiZone: / \+\d+$/.test(meta.zones[Number(zone)]), speed, abilities, newInForever: isNew === '1',
  };
});

const abilities = {};
for (const [name, list] of Object.entries(byAbility)) {
  if (/Attack/.test(name)) continue;
  abilities[name] = list.map((s) => ({ ...tips[s.id], rank: s.rank, spell: s.id, tp: s.tp }));
}
writeFileSync(join(DIR, 'pets.json'), JSON.stringify({ families: meta.fams, abilities, beasts }, null, 1));
console.log(`pets.json: ${beasts.length} beasts, ${Object.keys(abilities).length} abilities`);

// ---------------------------------------------------------------- PetData.lua (generated, not committed)
const lua = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
const clean = (s) => String(s || '').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const outLua = join(ROOT, 'addon', 'WowAssistant', 'PetData.lua');
const L = [
  `-- Generated by scripts/build-pets.mjs on ${new Date().toISOString().slice(0, 10)} from Wowhead Forever. Do not edit.`,
  'WowAssistantPets = {',
  '  -- abilities[name] = { { rank, spell, pet level, training points, focus, cooldown, description }, ... }',
  '  abilities = {',
  ...Object.entries(abilities).map(([name, list]) => `    [${lua(name)}] = {\n` + list.map((r) =>
    `      { ${r.rank}, ${r.spell}, ${r.level || 0}, ${r.tp || 0}, ${lua(clean(r.cost))}, ${lua(clean(r.cd))}, ${lua(clean(r.desc))} },`).join('\n') + '\n    },'),
  '  },',
  '  -- beasts: { npc, name, family, min level, max level, flags (R rare, E elite), zone, attack speed x100, "Ability:rank ..." }',
  '  beasts = {',
  ...beasts.map((b) => `    { ${b.npc}, ${lua(b.name)}, ${lua(b.family)}, ${b.min}, ${b.max}, ${lua((b.rare ? 'R' : '') + (b.elite ? 'E' : ''))}, ` +
    `${lua(b.zone)}, ${b.speed}, ${lua(b.abilities.map((a) => a.ability + ':' + a.rank).join(' '))} },`),
  '  },',
  '}',
  '',
];
writeFileSync(outLua, L.join('\n'));
console.log(`${outLua}: ${beasts.length} beasts`);
if (process.argv.includes('--install')) {
  const env = existsSync(join(ROOT, '.uploader.env')) ? readFileSync(join(ROOT, '.uploader.env'), 'utf8') : '';
  const wow = process.env.WOW_DIR ?? env.match(/^WOW_DIR=(.+)$/m)?.[1]?.trim() ?? 'F:/World of Warcraft/_forever_';
  const { copyFileSync } = await import('node:fs');
  copyFileSync(outLua, join(wow, 'Interface', 'AddOns', 'WowAssistant', 'PetData.lua'));
  console.log('telepítve');
}
